const font = 'Microsoft YaHei';

function run(text, options = {}) {
  return new TextRun({
    text,
    font,
    size: options.size ?? 24,
    bold: options.bold ?? false,
    color: options.color ?? '1F2937',
  });
}

function para(text, options = {}) {
  return new Paragraph({
    children: [run(text, options)],
    spacing: { before: options.before ?? 80, after: options.after ?? 80, line: 360 },
    alignment: options.align ?? AlignmentType.LEFT,
  });
}

function heading(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({
    heading: level,
    children: [run(text, { bold: true, size: level === HeadingLevel.HEADING_1 ? 32 : 28, color: '0F172A' })],
    spacing: { before: 160, after: 160 },
  });
}

function label(text) {
  return new Paragraph({
    children: [run(text, { bold: true, size: 22, color: '2563EB' })],
    spacing: { before: 120, after: 40 },
  });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

function addScriptPage(children, item, index) {
  if (index > 0) children.push(pageBreak());
  children.push(heading(item.title));
  children.push(label('讲解目标'));
  children.push(para(item.goal));
  children.push(label('讲稿'));
  for (const p of item.script) children.push(para(p));
  if (item.transition) {
    children.push(label('转场提示'));
    children.push(para(item.transition, { color: '475569' }));
  }
}

